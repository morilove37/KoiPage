//! Portable Magpie (window scaling) integration.
//!
//! Magpie exposes no IPC channel of its own, so this module treats it as an
//! external tool: locate `Magpie.exe`, report whether it is running, start it
//! before a game (when the user opts in), quit it on request, and read the
//! scaling hotkey out of Magpie's own configuration so the UI can show it.
//!
//! A full Magpie 0.12.1 release is embedded in the executable (built by
//! `build.rs` into `BUNDLED_FILES`) and unpacked to the app-local data directory
//! on first use, so the tool works offline without a separate install. The user
//! can still switch to their own `Magpie.exe` (`magpie_source = "custom"`).
//!
//! Everything here is best effort. A missing or broken Magpie installation must
//! never fail [`super::launch_game`] — the game still starts, just unscaled.

