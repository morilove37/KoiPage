/// Settings key holding the user-chosen `Magpie.exe` path (custom mode only).
pub const PATH_KEY: &str = "magpie_path";
/// Settings key holding `"1"` / `"0"` for starting Magpie before a game.
pub const AUTOSTART_KEY: &str = "magpie_autostart";
/// Settings key selecting the bundled or a user-supplied Magpie: `"bundled"`
/// (default) or `"custom"`.
pub const SOURCE_KEY: &str = "magpie_source";
/// Settings key holding the name of the scaling mode Magpie should default to.
pub const SCALING_MODE_KEY: &str = "magpie_scaling_mode";
/// Version of the bundled Magpie release (`Magpie-v0.12.1-x64.zip`).
pub const BUNDLED_VERSION: &str = "0.12.1";
/// Config schema folder Magpie 0.12 writes (`config/v4/config.json`).
const CONFIG_SCHEMA_DIR: &str = "v4";
/// Bundled recommended config: the maintainer's tuned Magpie scaling setup.
/// It is seeded only when Magpie has never produced a config on this machine;
/// an existing file is never overwritten.
const DEFAULT_CONFIG_BYTES: &[u8] =
    include_bytes!("../../resources/magpie-defaults/config.json");
const EXE_NAME: &str = "Magpie.exe";
/// Highest Magpie config schema version this build knows about; newer folders
/// are still preferred when present (see [`latest_config`]).
const CONFIG_ROOT_VERSION_MIN: u32 = 1;
const CONFIG_ROOT_VERSION_MAX: u32 = 9;
static EXTRACTION: Mutex<()> = Mutex::new(());

// Generated by `build.rs`: every file of the bundled Magpie release, keyed by
// its forward-slash relative path inside `resources/magpie`.
include!(concat!(env!("OUT_DIR"), "/magpie_files.rs"));

/// Returned by `magpie_status`.
#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct MagpieStatus {
    /// Resolved `Magpie.exe` path, or `None` when nothing was found.
    pub path: Option<String>,
    /// `bundled` (embedded copy), `custom` (settings), `process` (running
    /// instance), `auto` (well-known install path) or `none`.
    pub source: &'static str,
    /// File version, e.g. `0.12.1`.
    pub version: Option<String>,
    /// Whether a `Magpie.exe` process is alive right now.
    pub running: bool,
    /// Scaling hotkey from Magpie's config, e.g. `Win + Shift + A`.
    pub hotkey: Option<String>,
    /// Path of the Magpie `config.json` the hotkey was read from.
    pub config_path: Option<String>,
    /// Whether the embedded copy was unpacked successfully.
    pub bundled_available: bool,
    /// Version of the embedded copy (`0.12.1`), regardless of availability.
    pub bundled_version: String,
}

/// One live `Magpie.exe` process recovered from the process snapshot.
struct RunningProcess {
    pid: u32,
    path: Option<PathBuf>,
}

/// One scaling mode ("算法 + 滤镜链") from the local Magpie config.
