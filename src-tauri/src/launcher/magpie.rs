/// Decode one of Magpie's stored hotkeys.
///
/// Magpie keeps a hotkey as `key | (modifiers << 8)` where modifiers are the
/// Win32 `MOD_*` bits (ALT=1, CONTROL=2, SHIFT=4, WIN=8) — verified against a
/// real `v4/config.json`, e.g. `3137` = `0x0C41` = Win+Shift+A.
fn hotkey_label(value: u32) -> Option<String> {
    let key = (value & 0xFF) as u16;
    let modifiers = ((value >> 8) & 0xFF) as u16;
    if key == 0 {
        return None;
    }
    let mut parts: Vec<&str> = Vec::new();
    if modifiers & 0x08 != 0 {
        parts.push("Win");
    }
    if modifiers & 0x02 != 0 {
        parts.push("Ctrl");
    }
    if modifiers & 0x01 != 0 {
        parts.push("Alt");
    }
    if modifiers & 0x04 != 0 {
        parts.push("Shift");
    }
    let key = key_name(key);
    parts.push(&key);
    Some(parts.join(" + "))
}

fn key_name(key: u16) -> String {
    match key {
        0x08 => "Backspace".into(),
        0x09 => "Tab".into(),
        0x0D => "Enter".into(),
        0x1B => "Esc".into(),
        0x20 => "Space".into(),
        0x21 => "PageUp".into(),
        0x22 => "PageDown".into(),
        0x23 => "End".into(),
        0x24 => "Home".into(),
        0x25 => "Left".into(),
        0x26 => "Up".into(),
        0x27 => "Right".into(),
        0x28 => "Down".into(),
        0x2D => "Insert".into(),
        0x2E => "Delete".into(),
        0x5B => "LWin".into(),
        0x5C => "RWin".into(),
        0x41..=0x5A => char::from(key as u8).to_string(),
        0x30..=0x39 => char::from(key as u8).to_string(),
        0x70..=0x87 => format!("F{}", key - 0x6F),
        0xBA => ";".into(),
        0xBB => "=".into(),
        0xBC => ",".into(),
        0xBD => "-".into(),
        0xBE => ".".into(),
        0xBF => "/".into(),
        0xC0 => "`".into(),
        0xDB => "[".into(),
        0xDC => "\\".into(),
        0xDD => "]".into(),
        0xDE => "'".into(),
        _ => format!("VK {key:#04X}"),
    }
}

/// Highest-versioned `config/vN/config.json` below one config root.
fn latest_config(root: &Path) -> Option<PathBuf> {
    let Ok(entries) = std::fs::read_dir(root) else {
        return None;
    };
    let mut candidates: Vec<(u32, PathBuf)> = entries
        .flatten()
        .filter_map(|entry| {
            let name = entry.file_name().to_string_lossy().into_owned();
            let version = name.strip_prefix('v')?.parse::<u32>().ok()?;
            if !(CONFIG_ROOT_VERSION_MIN..=CONFIG_ROOT_VERSION_MAX).contains(&version) {
                return None;
            }
            let file = entry.path().join("config.json");
            file.is_file().then_some((version, file))
        })
        .collect();
    candidates.sort_by_key(|(version, _)| std::cmp::Reverse(*version));
    candidates.into_iter().next().map(|(_, file)| file)
}

/// Magpie's config location: portable copies keep it next to the executable,
/// installed copies use `%LOCALAPPDATA%\Magpie`.
fn config_path(exe: Option<&Path>) -> Option<PathBuf> {
    let mut roots = Vec::new();
    if let Some(exe) = exe {
        if let Some(parent) = exe.parent() {
            roots.push(parent.join("config"));
        }
    }
    if let Some(local) = std::env::var_os("LOCALAPPDATA") {
        roots.push(PathBuf::from(local).join("Magpie").join("config"));
    }
    roots.into_iter().find_map(|root| latest_config(&root))
}

fn read_hotkey(config: &Path) -> Option<String> {
    let text = std::fs::read_to_string(config).ok()?;
    let value: serde_json::Value = serde_json::from_str(&text).ok()?;
    let scale = value.get("shortcuts")?.get("scale")?.as_u64()?;
    u32::try_from(scale).ok().and_then(hotkey_label)
}

