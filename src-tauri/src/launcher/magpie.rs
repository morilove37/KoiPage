/// Resolve the active Magpie install.
///
/// `bundled` mode always prefers the embedded release (unpacking it if needed).
/// `custom` mode falls back from a valid user choice to a running instance (the
/// copy actually in use) and then to well-known install paths.
fn build_status(app: &AppHandle, source_setting: Option<&str>, custom: Option<&str>) -> MagpieStatus {
    let running = running_processes();
    let custom_mode = is_custom_source(source_setting);
    let (path, source) = if custom_mode {
        if let Some(path) = custom_path(custom) {
            (Some(path), "custom")
        } else if let Some(path) = running.iter().find_map(|process| process.path.clone()) {
            (Some(path), "process")
        } else if let Some(path) = detect() {
            (Some(path), "auto")
        } else {
            (None, "none")
        }
    } else {
        match bundled_path(app) {
            Ok(path) => (Some(path), "bundled"),
            Err(error) => {
                crate::app_warn!("[magpie] bundled extraction failed: {error}");
                (None, "none")
            }
        }
    };

    let config_path = config_path(path.as_deref());
    MagpieStatus {
        version: path.as_deref().and_then(version_of),
        path: path.as_ref().map(|path| path.to_string_lossy().into_owned()),
        source,
        running: !running.is_empty(),
        hotkey: config_path.as_deref().and_then(read_hotkey),
        config_path: config_path.map(|path| path.to_string_lossy().into_owned()),
        bundled_available: source == "bundled",
        bundled_version: BUNDLED_VERSION.into(),
    }
}

/// Why a launch has no tool to run, phrased for the mode the user picked.
fn missing_tool_error(source_setting: Option<&str>) -> CmdError {
    if is_custom_source(source_setting) {
        CmdError("未找到 Magpie，请在实用工具中选择 Magpie.exe。".into())
    } else {
        CmdError("内置 Magpie 暂不可用，请在实用工具中重新检查。".into())
    }
}

/// Spawn `Magpie.exe` detached; its tray icon is the app the user interacts with.
fn spawn_magpie(exe: &Path) -> CmdResult<()> {
    let mut command = std::process::Command::new(exe);
    if let Some(parent) = exe.parent() {
        command.current_dir(parent);
    }
    // CREATE_NEW_PROCESS_GROUP: do not join this app's console/CTRL group, so
    // stopping the game never takes Magpie down with it.
    #[cfg(windows)]
    {
        use std::os::windows::process::CommandExt;
        const CREATE_NEW_PROCESS_GROUP: u32 = 0x0000_0200;
        command.creation_flags(CREATE_NEW_PROCESS_GROUP);
    }
    command
        .spawn()
        .map(|_child| ())
        .map_err(|error| CmdError(format!("无法启动 Magpie {}：{error}", exe.display())))
}

/// `magpie_status` — resolved tool, version, live state, config and hotkey.
#[tauri::command]
