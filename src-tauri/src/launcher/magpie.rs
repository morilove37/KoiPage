/// A user-chosen path is only trusted when it still points at a file.
fn custom_path(custom: Option<&str>) -> Option<PathBuf> {
    custom
        .map(str::trim)
        .filter(|value| !value.is_empty())
        .map(PathBuf::from)
        .filter(|path| path.is_file())
}

/// Well-known install locations, in priority order.
///
/// Portable copies extracted anywhere else are covered by the running-process
/// lookup: a portable Magpie that is already running reports its own path, and
/// the frontend persists that value so the next cold start knows where it is.
fn detect() -> Option<PathBuf> {
    if let Some(value) = std::env::var_os("MAGPIE_PATH") {
        let value = PathBuf::from(value);
        if value.is_file() {
            return Some(value);
        }
        let nested = value.join(EXE_NAME);
        if nested.is_file() {
            return Some(nested);
        }
    }

    let mut candidates = Vec::new();
    if let Some(root) = std::env::var_os("LOCALAPPDATA") {
        candidates.push(PathBuf::from(&root).join("Programs").join("Magpie").join(EXE_NAME));
        candidates.push(PathBuf::from(&root).join("Magpie").join(EXE_NAME));
    }
    if let Some(root) = std::env::var_os("ProgramFiles") {
        candidates.push(PathBuf::from(root).join("Magpie").join(EXE_NAME));
    }
    if let Some(root) = std::env::var_os("ProgramFiles(x86)") {
        candidates.push(PathBuf::from(root).join("Magpie").join(EXE_NAME));
    }
    if let Some(root) = std::env::var_os("APPDATA") {
        candidates.push(PathBuf::from(root).join("Magpie").join(EXE_NAME));
    }
    candidates.into_iter().find(|candidate| candidate.is_file())
}

/// Is the user asking for their own `Magpie.exe` instead of the bundled copy?
///
/// Anything that is not explicitly `"custom"` resolves to the bundled release,
/// so a fresh install and a corrupted settings row both behave predictably.
fn is_custom_source(source: Option<&str>) -> bool {
    source
        .map(str::trim)
        .is_some_and(|value| value.eq_ignore_ascii_case("custom"))
}

