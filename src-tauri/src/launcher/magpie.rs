#[cfg(windows)]
mod platform {
    use std::ffi::OsStr;
    use std::os::windows::ffi::OsStrExt;
    use std::path::{Path, PathBuf};

    use windows_sys::Win32::Foundation::{CloseHandle, INVALID_HANDLE_VALUE};
    use windows_sys::Win32::Storage::FileSystem::{
        GetFileVersionInfoSizeW, GetFileVersionInfoW, VerQueryValueW,
    };
    use windows_sys::Win32::System::Diagnostics::ToolHelp::{
        CreateToolhelp32Snapshot, Process32FirstW, Process32NextW, PROCESSENTRY32W,
        TH32CS_SNAPPROCESS,
    };
    use windows_sys::Win32::System::Threading::{
        OpenProcess, QueryFullProcessImageNameW, TerminateProcess, PROCESS_NAME_WIN32,
        PROCESS_QUERY_LIMITED_INFORMATION, PROCESS_TERMINATE,
    };

    use super::{RunningProcess, EXE_NAME};

    /// VS_FIXEDFILEINFO; windows-sys exposes the constants but not this struct.
    #[repr(C)]
    struct FixedFileInfo {
        signature: u32,
        struc_version: u32,
        file_version_ms: u32,
        file_version_ls: u32,
        product_version_ms: u32,
        product_version_ls: u32,
        file_flags_mask: u32,
        file_flags: u32,
        file_os: u32,
        file_type: u32,
        file_subtype: u32,
        file_date_ms: u32,
        file_date_ls: u32,
    }

    fn wide(value: &OsStr) -> Vec<u16> {
        value.encode_wide().chain(std::iter::once(0)).collect()
    }

    /// File version from the executable's version resource, trailing zero parts
    /// trimmed (`0.12.1.0` → `0.12.1`).
    pub fn version_of(exe: &Path) -> Option<String> {
        let name = wide(exe.as_os_str());
        let mut handle = 0u32;
        let size = unsafe { GetFileVersionInfoSizeW(name.as_ptr(), &mut handle) };
        if size == 0 {
            return None;
        }
        let mut buffer = vec![0u8; size as usize];
        if unsafe { GetFileVersionInfoW(name.as_ptr(), 0, size, buffer.as_mut_ptr().cast()) } == 0 {
            return None;
        }
        let sub_block: [u16; 2] = [u16::from(b'\\'), 0];
        let mut pointer: *mut core::ffi::c_void = std::ptr::null_mut();
        let mut length = 0u32;
        let ok = unsafe {
            VerQueryValueW(
                buffer.as_ptr().cast(),
                sub_block.as_ptr(),
                &mut pointer,
                &mut length,
            )
        };
        if ok == 0 || pointer.is_null() || (length as usize) < std::mem::size_of::<FixedFileInfo>() {
            return None;
        }
        let info = unsafe { std::ptr::read_unaligned(pointer.cast::<FixedFileInfo>()) };
        let mut parts = vec![
            info.file_version_ms >> 16,
            info.file_version_ms & 0xFFFF,
            info.file_version_ls >> 16,
            info.file_version_ls & 0xFFFF,
        ]
        .into_iter()
        .map(|value| value.to_string())
        .collect::<Vec<_>>();
        while parts.len() > 1 && parts.last().is_some_and(|part| part == "0") {
            parts.pop();
        }
        Some(parts.join("."))
    }

    /// Every live `Magpie.exe`, with its image path when readable (elevated
    /// processes refuse the query, but still count as running).
    pub fn running_processes() -> Vec<RunningProcess> {
        let mut found = Vec::new();
        let snapshot = unsafe { CreateToolhelp32Snapshot(TH32CS_SNAPPROCESS, 0) };
        if snapshot == INVALID_HANDLE_VALUE {
            return found;
        }
        let mut entry: PROCESSENTRY32W = unsafe { std::mem::zeroed() };
        entry.dwSize = std::mem::size_of::<PROCESSENTRY32W>() as u32;
        let mut current = unsafe { Process32FirstW(snapshot, &mut entry) };
        while current != 0 {
            let length = entry
                .szExeFile
                .iter()
                .position(|&value| value == 0)
                .unwrap_or(entry.szExeFile.len());
            let name = String::from_utf16_lossy(&entry.szExeFile[..length]);
            if name.eq_ignore_ascii_case(EXE_NAME) {
                found.push(RunningProcess {
                    pid: entry.th32ProcessID,
                    path: process_path(entry.th32ProcessID),
                });
            }
            current = unsafe { Process32NextW(snapshot, &mut entry) };
        }
        unsafe { CloseHandle(snapshot) };
        found
    }

    fn process_path(pid: u32) -> Option<PathBuf> {
        let handle = unsafe { OpenProcess(PROCESS_QUERY_LIMITED_INFORMATION, 0, pid) };
        if handle.is_null() {
            return None;
        }
        let mut buffer = [0u16; 32768];
        let mut size = buffer.len() as u32;
        let ok = unsafe {
            QueryFullProcessImageNameW(handle, PROCESS_NAME_WIN32, buffer.as_mut_ptr(), &mut size)
        };
        unsafe { CloseHandle(handle) };
        if ok == 0 || size == 0 {
            return None;
        }
        Some(PathBuf::from(String::from_utf16_lossy(
            &buffer[..size as usize],
        )))
    }

    pub fn terminate(pid: u32) -> bool {
        let handle = unsafe { OpenProcess(PROCESS_TERMINATE, 0, pid) };
        if handle.is_null() {
            return false;
        }
        let ok = unsafe { TerminateProcess(handle, 1) };
        unsafe { CloseHandle(handle) };
        ok != 0
    }
}

