/// Unpack the embedded Magpie release into `directory` and return `Magpie.exe`.
///
/// Files that already exist are left alone — that keeps a user-replaced effect
/// or a Magpie self-update intact, and makes repeated calls cheap. The only
/// exception is a missing file (e.g. after an interrupted first extraction),
/// which is written again on the next call.
fn extract_to(directory: &Path) -> CmdResult<PathBuf> {
    let _guard = EXTRACTION
        .lock()
        .map_err(|_| CmdError("内置 Magpie 初始化锁不可用".into()))?;
    std::fs::create_dir_all(directory)
        .map_err(|error| CmdError(format!("无法准备内置 Magpie：{error}")))?;
    for (relative, bytes) in BUNDLED_FILES {
        let path = directory.join(relative);
        if path.is_file() {
            continue;
        }
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)
                .map_err(|error| CmdError(format!("无法准备内置 Magpie 目录：{error}")))?;
        }
        std::fs::write(&path, bytes)
            .map_err(|error| CmdError(format!("内置 Magpie 文件准备失败 {relative}：{error}")))?;
    }
    Ok(directory.join(EXE_NAME))
}

/// Path of the bundled `Magpie.exe`, extracting the release on first use.
///
/// Lives under the app-local data directory rather than next to the executable:
/// Magpie writes its cache and logs beside itself, and an installed app's own
/// directory may be read-only for a standard user.
pub fn bundled_path(app: &AppHandle) -> CmdResult<PathBuf> {
    let directory = app
        .path()
        .app_local_data_dir()
        .map_err(|error| CmdError(error.to_string()))?
        .join("tools")
        .join("magpie")
        .join(BUNDLED_VERSION);
    extract_to(&directory)
}

