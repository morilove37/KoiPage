/// `magpie_scaling_config` — scaling modes and the current default.
///
/// An existing local Magpie config wins; otherwise the bundled maintainer
/// default is returned, so a fresh machine already shows the intended presets.
#[tauri::command]
pub async fn magpie_scaling_config(app: AppHandle) -> CmdResult<ScalingConfig> {
    let (value, config_path, using_app_defaults) = match current_config_path(&app).await? {
        Some(config) => (
            read_config_value(&config)?,
            Some(config.to_string_lossy().into_owned()),
            false,
        ),
        None => (default_config_value()?, None, true),
    };
    Ok(ScalingConfig {
        modes: scaling_modes(&value),
        default_index: default_scaling_index(&value),
        config_path,
        using_app_defaults,
    })
}

/// `magpie_scaling_set` — remember a default scaling mode and, when Magpie is
/// not running, write it into the local config immediately. While Magpie runs it
/// owns that file, so the value is only stored and applied on the next start.
#[tauri::command]
pub async fn magpie_scaling_set(app: AppHandle, mode: String) -> CmdResult<ScalingSetResult> {
    let db = pool(&app).await?;
    let mode = mode.trim().to_string();
    if mode.is_empty() {
        return Err(CmdError("缩放模式名称不能为空".into()));
    }

    let exe = current_exe(&app).await?;
    let config = match config_path(exe.as_deref()) {
        Some(config) => config,
        None => {
            // First run: create Magpie's config from the bundled default so the
            // chosen mode can be applied now instead of after Magpie writes one.
            let target = default_config_file(exe.as_deref())
                .ok_or_else(|| CmdError("无法找到 Magpie 配置目录".into()))?;
            write_default_config(&target)?;
            target
        }
    };

    // Reject a mode that disappeared from the config instead of persisting a
    // name that can never be applied.
    let value = read_config_value(&config)?;
    if !scaling_modes(&value).iter().any(|item| item.name == mode) {
        return Err(CmdError(format!("本机 Magpie 配置中没有名为「{mode}」的缩放模式")));
    }
    store_setting(&db, SCALING_MODE_KEY, &mode).await?;

    let config_path = Some(config.to_string_lossy().into_owned());
    if !running_processes().is_empty() {
        return Ok(ScalingSetResult {
            applied: false,
            reason: Some("running"),
            config_path,
        });
    }
    write_scaling_mode(&config, &mode)?;
    Ok(ScalingSetResult {
        applied: true,
        reason: None,
        config_path,
    })
}

/// `magpie_scaling_reset` — replace the local Magpie config with the bundled
/// maintainer setup and drop the remembered mode, so the shipped defaults apply.
///
/// Refused while Magpie is running: it owns the file and would save over the
/// restored config on exit.
#[tauri::command]
pub async fn magpie_scaling_reset(app: AppHandle) -> CmdResult<ScalingResetResult> {
    let db = pool(&app).await?;
    if !running_processes().is_empty() {
        return Err(CmdError("Magpie 正在运行，请先退出 Magpie 再恢复默认配置。".into()));
    }
    // Validate the bundled payload before touching the user's file.
    default_config_value()?;

    let exe = current_exe(&app).await?;
    let config = match config_path(exe.as_deref()) {
        Some(config) => config,
        None => default_config_file(exe.as_deref())
            .ok_or_else(|| CmdError("无法找到 Magpie 配置目录".into()))?,
    };
    let backup = restore_default_config(&config)?;
    sqlx::query("DELETE FROM settings WHERE key = ?")
        .bind(SCALING_MODE_KEY)
        .execute(&db)
        .await?;
    Ok(ScalingResetResult {
        config_path: config.to_string_lossy().into_owned(),
        backup_path: backup.map(|path| path.to_string_lossy().into_owned()),
    })
}

/// `magpie_launch` — start Magpie unless it is already running.
///
/// Returns `true` when a new process was spawned, `false` when Magpie was
/// already running.
#[tauri::command]
pub async fn magpie_launch(app: AppHandle) -> CmdResult<bool> {
    let db = pool(&app).await?;
    let source = super::setting(&db, SOURCE_KEY).await?;
    let custom = super::setting(&db, PATH_KEY).await?;
    let status = build_status(&app, source.as_deref(), custom.as_deref());
    if status.running {
        return Ok(false);
    }
    let exe = status
        .path
        .as_deref()
        .map(PathBuf::from)
        .ok_or_else(|| missing_tool_error(source.as_deref()))?;
    // Seed the bundled default config on first run and apply the stored mode
    // before Magpie reads its config.
    let scaling = super::setting(&db, SCALING_MODE_KEY).await?;
    apply_stored_scaling_mode(ensure_default_config(Some(&exe)).as_deref(), scaling.as_deref());
    spawn_magpie(&exe)?;
    Ok(true)
}

/// `magpie_quit` — terminate running Magpie processes.
///
/// Magpie commonly runs elevated; terminating it from this non-elevated process
/// then fails with access denied, which is reported so the UI can point at the
/// tray icon instead of pretending it worked.
#[tauri::command]
pub fn magpie_quit() -> CmdResult<bool> {
    let processes = running_processes();
    if processes.is_empty() {
        return Ok(false);
    }
    let mut terminated = 0;
    for process in &processes {
        if terminate(process.pid) {
            terminated += 1;
        }
    }
    if terminated == 0 {
        return Err(CmdError(
            "无法退出 Magpie：它可能以管理员权限运行，请在系统托盘中右键 Magpie 图标退出。".into(),
        ));
    }
    Ok(true)
}

/// Start Magpie before a game when the user enabled the autostart setting.
///
/// Best effort by design: a missing tool must not block the launch. The bundled
/// release is unpacked here too, so the very first game launch already works.
pub fn is_running() -> bool { !running_processes().is_empty() }

pub fn autostart(
    app: &AppHandle,
    source_setting: Option<&str>,
    custom: Option<&str>,
    scaling_mode: Option<&str>,
) {
    if !running_processes().is_empty() {
        return;
    }
    let exe = if is_custom_source(source_setting) {
        match custom_path(custom).or_else(detect) {
            Some(path) => path,
            None => return,
        }
    } else {
        match bundled_path(app) {
            Ok(path) => path,
            Err(error) => {
                crate::app_warn!("[magpie] autostart skipped: {error}");
                return;
            }
        }
    };
    let config = ensure_default_config(Some(&exe));
    apply_stored_scaling_mode(config.as_deref(), scaling_mode);
    if let Err(error) = spawn_magpie(&exe) {
        crate::app_warn!("[magpie] autostart failed: {error}");
    }
}

