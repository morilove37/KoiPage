fn read_config_value(config: &Path) -> CmdResult<serde_json::Value> {
    let text = std::fs::read_to_string(config)
        .map_err(|error| CmdError(format!("无法读取本机 Magpie 配置：{error}")))?;
    serde_json::from_str(&text)
        .map_err(|error| CmdError(format!("本机 Magpie 配置格式无法解析：{error}")))
}

fn scaling_modes(value: &serde_json::Value) -> Vec<ScalingModeInfo> {
    value
        .get("scalingModes")
        .and_then(serde_json::Value::as_array)
        .map(|modes| {
            modes
                .iter()
                .filter_map(|mode| {
                    let name = mode.get("name")?.as_str()?.to_string();
                    let effects = mode
                        .get("effects")
                        .and_then(serde_json::Value::as_array)
                        .map(|effects| {
                            effects
                                .iter()
                                .filter_map(|effect| {
                                    effect.get("name")?.as_str().map(str::to_string)
                                })
                                .collect()
                        })
                        .unwrap_or_default();
                    Some(ScalingModeInfo { name, effects })
                })
                .collect()
        })
        .unwrap_or_default()
}

fn default_scaling_index(value: &serde_json::Value) -> Option<usize> {
    value
        .get("profiles")?
        .as_array()?
        .first()?
        .get("scalingMode")?
        .as_u64()
        .and_then(|index| usize::try_from(index).ok())
}

/// Make `mode_name` the default scaling mode of Magpie's first profile.
///
/// Only one integer changes; every other field is round-tripped through
/// `serde_json::Value`. A one-time backup (`config.koipage-backup.json`) is kept
/// next to the original, and the file is replaced atomically via a temp rename.
fn write_scaling_mode(config: &Path, mode_name: &str) -> CmdResult<()> {
    let mut value = read_config_value(config)?;
    let modes = value
        .get("scalingModes")
        .and_then(serde_json::Value::as_array)
        .ok_or_else(|| CmdError("本机 Magpie 配置缺少缩放模式列表".into()))?;
    let index = modes
        .iter()
        .position(|mode| mode.get("name").and_then(serde_json::Value::as_str) == Some(mode_name))
        .ok_or_else(|| CmdError(format!("本机 Magpie 配置中没有名为「{mode_name}」的缩放模式")))?;
    let profiles = value
        .get_mut("profiles")
        .and_then(serde_json::Value::as_array_mut)
        .ok_or_else(|| CmdError("本机 Magpie 配置缺少默认配置（profiles）".into()))?;
    let profile = profiles
        .first_mut()
        .ok_or_else(|| CmdError("本机 Magpie 配置缺少默认配置（profiles）".into()))?;
    profile["scalingMode"] = serde_json::Value::from(index);

    let backup = config.with_file_name("config.koipage-backup.json");
    if !backup.is_file() {
        std::fs::copy(config, &backup)
            .map_err(|error| CmdError(format!("无法备份本机 Magpie 配置：{error}")))?;
    }
    let temporary = config.with_file_name("config.koipage-tmp.json");
    let serialized = serde_json::to_string_pretty(&value)
        .map_err(|error| CmdError(format!("无法序列化本机 Magpie 配置：{error}")))?;
    std::fs::write(&temporary, serialized)
        .map_err(|error| CmdError(format!("无法写入本机 Magpie 配置：{error}")))?;
    std::fs::rename(&temporary, config)
        .map_err(|error| CmdError(format!("无法更新本机 Magpie 配置：{error}")))?;
    Ok(())
}

/// The bundled default config as a JSON value.
fn default_config_value() -> CmdResult<serde_json::Value> {
    serde_json::from_slice(DEFAULT_CONFIG_BYTES)
        .map_err(|error| CmdError(format!("内置 Magpie 默认配置无法解析：{error}")))
}

/// Where Magpie would create its config on this machine.
fn default_config_file(exe: Option<&Path>) -> Option<PathBuf> {
    if let Some(exe) = exe {
        if let Some(parent) = exe.parent() {
            let root = parent.join("config");
            if root.is_dir() {
                return Some(root.join(CONFIG_SCHEMA_DIR).join("config.json"));
            }
        }
    }
    std::env::var_os("LOCALAPPDATA").map(|root| {
        PathBuf::from(root)
            .join("Magpie")
            .join("config")
            .join(CONFIG_SCHEMA_DIR)
            .join("config.json")
    })
}

/// Write the bundled default config unless the path already exists.
///
/// `create_new` makes this race-safe: if Magpie (or another launch) creates the
/// file at the same moment, the existing one wins and is left untouched.
fn write_default_config(path: &Path) -> CmdResult<bool> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)
            .map_err(|error| CmdError(format!("无法创建 Magpie 配置目录：{error}")))?;
    }
    let mut file = match std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(path)
    {
        Ok(file) => file,
        Err(error) if error.kind() == std::io::ErrorKind::AlreadyExists => return Ok(false),
        Err(error) => {
            return Err(CmdError(format!("无法写入内置 Magpie 默认配置：{error}")));
        }
    };
    use std::io::Write;
    file.write_all(DEFAULT_CONFIG_BYTES)
        .map_err(|error| CmdError(format!("无法写入内置 Magpie 默认配置：{error}")))?;
    Ok(true)
}

/// Ensure a config exists, seeding the bundled default when Magpie has never
/// run on this machine. Best effort: failures must not stop a launch.
fn ensure_default_config(exe: Option<&Path>) -> Option<PathBuf> {
    if let Some(existing) = config_path(exe) {
        return Some(existing);
    }
    let target = default_config_file(exe)?;
    match write_default_config(&target) {
        Ok(_) => Some(target),
        Err(error) => {
            crate::app_warn!("[magpie] could not seed the bundled default config: {error}");
            None
        }
    }
}

/// Replace the config at `config` with the bundled default.
///
/// A previous file is copied to `config.koipage-before-reset.json` first, so the
/// change can be undone by hand. Returns the backup path when one was created.
fn restore_default_config(config: &Path) -> CmdResult<Option<PathBuf>> {
    let backup = if config.is_file() {
        let backup_path = config.with_file_name("config.koipage-before-reset.json");
        std::fs::copy(config, &backup_path)
            .map_err(|error| CmdError(format!("无法备份本机 Magpie 配置：{error}")))?;
        Some(backup_path)
    } else {
        None
    };
    if let Some(parent) = config.parent() {
        std::fs::create_dir_all(parent)
            .map_err(|error| CmdError(format!("无法创建 Magpie 配置目录：{error}")))?;
    }
    let temporary = config.with_file_name("config.koipage-tmp.json");
    std::fs::write(&temporary, DEFAULT_CONFIG_BYTES)
        .map_err(|error| CmdError(format!("无法写入内置 Magpie 默认配置：{error}")))?;
    std::fs::rename(&temporary, config)
        .map_err(|error| CmdError(format!("无法更新本机 Magpie 配置：{error}")))?;
    Ok(backup)
}

/// Write the stored default scaling mode into Magpie's config before it starts.
///
/// Best effort: a missing config only means Magpie has not run on this machine
/// yet; the stored preference is applied on a later launch once it exists.
fn apply_stored_scaling_mode(config: Option<&Path>, mode: Option<&str>) {
    let (Some(config), Some(mode)) = (config, mode) else {
        return;
    };
    if let Err(error) = write_scaling_mode(config, mode) {
        crate::app_warn!("[magpie] could not apply the stored scaling mode: {error}");
    }
}

/// Magpie executable for the currently selected source (bundled/custom).
async fn current_exe(app: &AppHandle) -> CmdResult<Option<PathBuf>> {
    let db = pool(app).await?;
    let source = super::setting(&db, SOURCE_KEY).await?;
    let custom = super::setting(&db, PATH_KEY).await?;
    Ok(if is_custom_source(source.as_deref()) {
        custom_path(custom.as_deref()).or_else(detect)
    } else {
        bundled_path(app).ok()
    })
}

/// The config that belongs to the currently selected Magpie tool.
async fn current_config_path(app: &AppHandle) -> CmdResult<Option<PathBuf>> {
    Ok(config_path(current_exe(app).await?.as_deref()))
}

async fn store_setting(db: &Pool<Sqlite>, key: &str, value: &str) -> CmdResult<()> {
    sqlx::query(
        "INSERT INTO settings (key, value) VALUES (?, ?) \
         ON CONFLICT(key) DO UPDATE SET value = excluded.value",
    )
    .bind(key)
    .bind(value)
    .execute(db)
    .await?;
    Ok(())
}

