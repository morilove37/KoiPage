//! Archive extraction for the import flow.
//!
//! Galgame releases often arrive as `.zip`, `.rar`, `.7z` or split volumes
//! (`.part1.rar`, `.r00`, `.7z.001`, `.z01`, …). Windows cannot extract RAR
//! itself, so the app ships 7-Zip's console build (`7z.exe` + `7z.dll`) and
//! unpacks it to the app-local data directory on first use. Zip, RAR and split
//! archives all go through the same executable, which also keeps password
//! handling in one place.
//!
//! A command call handles exactly one archive: batch imports need a password
//! prompt between archives, so the frontend groups the drops, calls this
//! command per group, and retries with the entered password when the result is
//! [`ExtractStatus::PasswordRequired`] or [`ExtractStatus::WrongPassword`].
//!
//! This module never decides where a game lives beyond the requested
//! destination: it creates `<destination>/<archive name>` (unique if needed) and
//! reports the folder back so the caller can scan it immediately.

use std::io::{BufRead, BufReader};
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

use serde::Serialize;
use tauri::{AppHandle, Emitter, Manager};

use crate::commands::error::{CmdError, CmdResult};

/// Bundled 7-Zip version. The directory layout mirrors Magpie/Locale Emulator.
pub const BUNDLED_VERSION: &str = "26.01";

/// Progress event emitted while 7-Zip runs. Payload: [`ExtractProgress`].
pub const EXTRACT_PROGRESS_EVENT: &str = "archive-extract-progress";

// Generated by `build.rs`: every file of the bundled 7-Zip console build.
include!(concat!(env!("OUT_DIR"), "/sevenzip_files.rs"));

/// One dropped archive family (all volumes collapse to a single entry).
#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ArchiveGroup {
    /// First volume / the file to pass to 7-Zip.
    pub primary: String,
    /// Folder name derived from the archive name.
    pub display_name: String,
    /// Every volume the user dropped for this archive.
    pub paths: Vec<String>,
}

/// Outcome of one extraction attempt.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub enum ExtractStatus {
    Ok,
    /// The archive is encrypted and no password was supplied yet.
    PasswordRequired,
    /// A password was supplied but 7-Zip rejected it.
    WrongPassword,
    Failed,
}

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ExtractResult {
    pub status: ExtractStatus,
    /// The normalized first volume that was extracted.
    pub archive: String,
    /// Folder created for the archive (empty when failed before creation).
    pub target_dir: String,
    /// Human-readable diagnostic for failures.
    pub message: Option<String>,
    /// Archive files moved to the Recycle Bin after a successful extraction.
    pub deleted_files: Vec<String>,
    /// Set when the originals could not be moved to the Recycle Bin.
    pub cleanup_warning: Option<String>,
}

impl ExtractResult {
    fn failed(status: ExtractStatus, archive: String, message: Option<String>) -> Self {
        Self {
            status,
            archive,
            target_dir: String::new(),
            message,
            deleted_files: Vec::new(),
            cleanup_warning: None,
        }
    }
}

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ExtractProgress {
    pub archive: String,
    pub percent: u8,
}

/// `archive_group` — collapse dropped paths into archive families.
///
/// Accepts any volume of a set (`Game.part2.rar`, `Game.r01`, `Game.7z.002`,
/// `Game.z01`, …) and returns the first volume to hand to 7-Zip. Unsupported
/// paths are ignored (the frontend filters by extension as well).
#[tauri::command]
pub fn archive_group(paths: Vec<String>) -> CmdResult<Vec<ArchiveGroup>> {
    Ok(group_archives(&paths))
}

/// `archive_extract` — extract one archive into `<destination>/<name>`.
#[tauri::command]
pub async fn archive_extract(
    app: AppHandle,
    archive: String,
    destination: String,
    password: Option<String>,
) -> CmdResult<ExtractResult> {
    let archive = required_path(&archive, "archive")?;
    let destination = required_path(&destination, "destination")?;
    if destination.exists() && !destination.is_dir() {
        return Err(CmdError(format!(
            "解压目录不是文件夹：{}",
            destination.display()
        )));
    }
    std::fs::create_dir_all(&destination)
        .map_err(|error| CmdError(format!("无法创建解压目录：{error}")))?;

    let app_for_work = app.clone();
    tauri::async_runtime::spawn_blocking(move || {
        extract_blocking(&app_for_work, &archive, &destination, password.as_deref())
    })
    .await
    .map_err(|error| CmdError(format!("解压任务失败：{error}")))?
}

/// Pure grouping used by [`archive_group`] and the unit tests.
fn group_archives(paths: &[String]) -> Vec<ArchiveGroup> {
    let mut groups: Vec<ArchiveGroup> = Vec::new();
    for raw in paths {
        let Some(first) = first_volume(Path::new(raw)) else {
            continue;
        };
        let display_name = folder_name_for(&first);
        let primary = first.to_string_lossy().into_owned();
        let key = primary.to_lowercase();
        if let Some(existing) = groups
            .iter_mut()
            .find(|group| group.primary.to_lowercase() == key)
        {
            if !existing
                .paths
                .iter()
                .any(|path| path.eq_ignore_ascii_case(raw))
            {
                existing.paths.push(raw.clone());
            }
            continue;
        }
        groups.push(ArchiveGroup {
            primary,
            display_name,
            paths: vec![raw.clone()],
        });
    }
    groups
}

/// Resolve any volume of a set to its first volume.
///
/// Returns `None` for files that are not a supported archive or volume.
fn first_volume(path: &Path) -> Option<PathBuf> {
    let name = path.file_name()?.to_str()?;
    let lower = name.to_ascii_lowercase();
    let parent = path.parent().unwrap_or_else(|| Path::new("."));
    let count = lower.chars().count();

    // `Game.part02.rar` → `Game.part01.rar`; preserve zero padding width.
    if let Some(position) = lower.rfind(".part") {
        if lower.ends_with(".rar") {
            let digits = &lower[position + 5..lower.len() - 4];
            if !digits.is_empty() && digits.chars().all(|ch| ch.is_ascii_digit()) {
                let width = digits.chars().count();
                let first = format!("{:0width$}", 1, width = width);
                return Some(parent.join(format!(
                    "{}.part{}.rar",
                    &name[..position],
                    first
                )));
            }
        }
    }

    // Single RAR / old-style RAR volume (`.r00`, `.r01`, … → base `.rar`).
    if lower.ends_with(".rar") {
        return Some(path.to_path_buf());
    }
    if let Some(position) = lower.rfind(".r") {
        let suffix = &lower[position + 2..];
        if suffix.len() >= 2 && suffix.chars().all(|ch| ch.is_ascii_digit()) {
            return Some(parent.join(format!("{}.rar", &name[..position])));
        }
    }

    // Split ZIP: `.z01`, `.z02`, … → base `.zip`; plain zip stays itself.
    if lower.ends_with(".zip") {
        return Some(path.to_path_buf());
    }
    if let Some(position) = lower.rfind(".z") {
        let suffix = &lower[position + 2..];
        if suffix.len() >= 2 && suffix.chars().all(|ch| ch.is_ascii_digit()) {
            return Some(parent.join(format!("{}.zip", &name[..position])));
        }
    }

    // Three-digit split volumes: `.7z.001`, `.zip.001`, `.001`.
    if lower.ends_with(".001") {
        return Some(path.to_path_buf());
    }
    if let Some(position) = lower.rfind('.') {
        let suffix = &lower[position + 1..];
        if suffix.len() == 3 && suffix.chars().all(|ch| ch.is_ascii_digit()) {
            return Some(parent.join(format!("{}.001", &name[..position])));
        }
    }

    if lower.ends_with(".7z") {
        return Some(path.to_path_buf());
    }
    let _ = count;
    None
}

/// Folder name derived from the first volume, without archive/volume suffixes.
fn folder_name_for(archive: &Path) -> String {
    let mut name = archive
        .file_name()
        .and_then(|value| value.to_str())
        .unwrap_or("解压游戏")
        .to_string();

    // Strip archive extension and volume markers in any order they appear:
    // `Game.part1.rar` (extension last) and `Game.7z.001` (volume last).
    loop {
        let lower = name.to_ascii_lowercase();
        let mut changed = false;
        if let Some(stripped) = strip_volume_marker(&name) {
            name = stripped;
            changed = true;
        } else {
            for suffix in [".rar", ".zip", ".7z"] {
                if lower.ends_with(suffix) {
                    name.truncate(name.len() - suffix.len());
                    changed = true;
                    break;
                }
            }
        }
        if !changed {
            break;
        }
    }
    sanitize_folder_name(&name)
}

fn strip_volume_marker(value: &str) -> Option<String> {
    let lower = value.to_ascii_lowercase();
    if let Some(position) = lower.rfind(".part") {
        let digits = &lower[position + 5..];
        if !digits.is_empty() && digits.chars().all(|ch| ch.is_ascii_digit()) {
            return Some(value[..position].to_string());
        }
    }
    if let Some(position) = lower.rfind('.') {
        let suffix = &lower[position + 1..];
        if suffix.len() == 3 {
            let digits = if suffix.chars().all(|ch| ch.is_ascii_digit()) {
                true
            } else if suffix.starts_with('r') || suffix.starts_with('z') {
                suffix[1..].chars().all(|ch| ch.is_ascii_digit())
            } else {
                false
            };
            if digits {
                return Some(value[..position].to_string());
            }
        }
    }
    None
}

fn sanitize_folder_name(value: &str) -> String {
    let cleaned: String = value
        .trim()
        .trim_end_matches('.')
        .chars()
        .map(|ch| match ch {
            '<' | '>' | ':' | '"' | '/' | '\\' | '|' | '?' | '*' => '_',
            _ => ch,
        })
        .collect();
    let cleaned = cleaned.trim().trim_end_matches('.');
    if cleaned.is_empty() {
        "解压游戏".to_string()
    } else {
        cleaned.chars().take(80).collect()
    }
}

fn unique_target(destination: &Path, name: &str) -> PathBuf {
    let first = destination.join(name);
    if !first.exists() {
        return first;
    }
    for index in 2..1000 {
        let candidate = destination.join(format!("{name} ({index})"));
        if !candidate.exists() {
            return candidate;
        }
    }
    destination.join(format!("{name} (999)"))
}

fn required_path(value: &str, field: &str) -> CmdResult<PathBuf> {
    let trimmed = value.trim();
    if trimmed.is_empty() {
        return Err(CmdError(format!("{field} 不能为空")));
    }
    Ok(PathBuf::from(trimmed))
}

fn extract_blocking(
    app: &AppHandle,
    archive: &Path,
    destination: &Path,
    password: Option<&str>,
) -> CmdResult<ExtractResult> {
    let Some(first) = first_volume(archive) else {
        return Ok(ExtractResult::failed(
            ExtractStatus::Failed,
            archive.to_string_lossy().into_owned(),
            Some("不支持的压缩格式".to_string()),
        ));
    };
    if !first.is_file() {
        return Ok(ExtractResult::failed(
            ExtractStatus::Failed,
            first.to_string_lossy().into_owned(),
            Some(format!(
                "找不到分卷起始文件：{}",
                first
                    .file_name()
                    .and_then(|name| name.to_str())
                    .unwrap_or_default()
            )),
        ));
    }

    let seven_zip = seven_zip_path(app)?;
    let used_password = password
        .map(str::trim)
        .is_some_and(|value| !value.is_empty());

    // Listing is cheap and tells us whether the archive is encrypted even when
    // 7-Zip's extraction error text is terse (it sometimes only prints
    // "Sub items Errors"), so password prompts do not depend on message parsing.
    let probe = probe_archive(&seven_zip, &first, password);
    match probe {
        Probe::PasswordProblem => {
            return Ok(ExtractResult::failed(
                if used_password {
                    ExtractStatus::WrongPassword
                } else {
                    ExtractStatus::PasswordRequired
                },
                first.to_string_lossy().into_owned(),
                Some("压缩包已加密，需要有效的密码。".to_string()),
            ));
        }
        Probe::Encrypted if !used_password => {
            return Ok(ExtractResult::failed(
                ExtractStatus::PasswordRequired,
                first.to_string_lossy().into_owned(),
                Some("该压缩包已加密，请输入密码。".to_string()),
            ));
        }
        _ => {}
    }

    let destination_name = folder_name_for(&first);
    let target = unique_target(destination, &destination_name);
    if let Err(error) = std::fs::create_dir_all(&target) {
        return Err(CmdError(format!("无法创建解压目录：{error}")));
    }

    let archive_label = first.to_string_lossy().into_owned();
    let mut command = Command::new(&seven_zip);
    command
        .arg("x")
        .arg(&first)
        .arg(format!("-o{}", target.display()))
        .arg("-y")
        .arg("-bso1")
        .arg("-bsp1")
        .arg("-bse1");
    if let Some(password) = password.map(str::trim).filter(|value| !value.is_empty()) {
        command.arg(format!("-p{password}"));
    }
    command
        .stdin(Stdio::null())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped());

    #[cfg(windows)]
    {
        use std::os::windows::process::CommandExt;
        const CREATE_NO_WINDOW: u32 = 0x0800_0000;
        command.creation_flags(CREATE_NO_WINDOW);
    }

    let mut child = match command.spawn() {
        Ok(child) => child,
        Err(error) => {
            let _ = std::fs::remove_dir_all(&target);
            return Ok(ExtractResult::failed(
                ExtractStatus::Failed,
                archive_label,
                Some(format!("无法启动内置 7-Zip：{error}")),
            ));
        }
    };

    let stderr = child.stderr.take();
    let stderr_reader = std::thread::spawn(move || {
        let mut text = String::new();
        if let Some(stderr) = stderr {
            for line in BufReader::new(stderr).lines().map_while(Result::ok) {
                text.push_str(&line);
                text.push('\n');
            }
        }
        text
    });

    let mut stdout_text = String::new();
    let mut last_percent: Option<u8> = None;
    if let Some(stdout) = child.stdout.take() {
        for line in BufReader::new(stdout).lines().map_while(Result::ok) {
            if let Some(percent) = parse_progress(&line) {
                if last_percent != Some(percent) {
                    last_percent = Some(percent);
                    let _ = app.emit(
                        EXTRACT_PROGRESS_EVENT,
                        ExtractProgress {
                            archive: archive_label.clone(),
                            percent,
                        },
                    );
                }
            } else {
                stdout_text.push_str(&line);
                stdout_text.push('\n');
            }
        }
    }
    let status = child.wait();
    let stderr_text = stderr_reader.join().unwrap_or_default();
    let output = format!("{stdout_text}\n{stderr_text}");
    let success = status
        .as_ref()
        .map(|status| status.success())
        .unwrap_or(false);

    if success {
        // The user asked for the original archives to be cleaned up after a
        // successful extraction. Move them to the Recycle Bin so the action is
        // recoverable; a cleanup failure must never fail the extraction itself.
        let (deleted_files, cleanup_warning) = remove_originals(&first);
        return Ok(ExtractResult {
            status: ExtractStatus::Ok,
            archive: archive_label,
            target_dir: target.to_string_lossy().into_owned(),
            message: None,
            deleted_files,
            cleanup_warning,
        });
    }

    // A failed extraction must not leave a half-populated folder behind: the
    // retry after a password prompt starts from a clean directory.
    let _ = std::fs::remove_dir_all(&target);
    let status = match probe {
        Probe::Encrypted | Probe::PasswordProblem => {
            if used_password {
                ExtractStatus::WrongPassword
            } else {
                ExtractStatus::PasswordRequired
            }
        }
        Probe::Clean => classify_output(&output, used_password),
    };
    let message = output
        .lines()
        .rev()
        .find(|line| !line.trim().is_empty())
        .map(str::trim)
        .map(|line| line.chars().take(600).collect::<String>());

    Ok(ExtractResult::failed(status, archive_label, message))
}

/// Volume / single-archive files that belong to the same archive set as `first`.
///
/// Used after a successful extraction to remove the original files. Only names
/// matching the archive's own volume pattern are returned, so a stray
/// same-stem document (`Game.txt`) is never touched.
fn archive_volumes(first: &Path) -> Vec<PathBuf> {
    let Some(name) = first.file_name().and_then(|value| value.to_str()) else {
        return vec![first.to_path_buf()];
    };
    let lower = name.to_ascii_lowercase();
    let Some(parent) = first.parent() else {
        return vec![first.to_path_buf()];
    };
    let entries: Vec<(String, PathBuf)> = match std::fs::read_dir(parent) {
        Ok(entries) => entries
            .flatten()
            .filter(|entry| entry.file_type().map(|kind| kind.is_file()).unwrap_or(false))
            .filter_map(|entry| {
                let path = entry.path();
                let name = path.file_name()?.to_str()?.to_ascii_lowercase();
                Some((name, path))
            })
            .collect(),
        Err(_) => Vec::new(),
    };

    let mut volumes: Vec<PathBuf> = Vec::new();
    let mut push = |path: PathBuf| {
        if !volumes.iter().any(|existing| existing == &path) {
            volumes.push(path);
        }
    };

    if let Some(position) = lower.rfind(".part") {
        if lower.ends_with(".rar") {
            let prefix = format!("{}.part", &name[..position].to_ascii_lowercase());
            for (entry_lower, path) in &entries {
                let Some(middle) = entry_lower
                    .strip_prefix(&prefix)
                    .and_then(|rest| rest.strip_suffix(".rar"))
                else {
                    continue;
                };
                if !middle.is_empty() && middle.chars().all(|ch| ch.is_ascii_digit()) {
                    push(path.clone());
                }
            }
        }
    } else if lower.ends_with(".rar") {
        let stem = lower.trim_end_matches(".rar").to_string();
        let old_volume_prefix = format!("{stem}.");
        for (entry_lower, path) in &entries {
            let is_base = entry_lower == &lower;
            let is_old_volume = entry_lower
                .strip_prefix(&old_volume_prefix)
                .is_some_and(|rest| {
                    rest.len() == 3
                        && rest.starts_with('r')
                        && rest[1..].chars().all(|ch| ch.is_ascii_digit())
                });
            if is_base || is_old_volume {
                push(path.clone());
            }
        }
    } else if lower.ends_with(".zip") {
        let stem = lower.trim_end_matches(".zip").to_string();
        let split_prefix = format!("{stem}.");
        for (entry_lower, path) in &entries {
            let is_base = entry_lower == &lower;
            let is_split = entry_lower
                .strip_prefix(&split_prefix)
                .is_some_and(|rest| {
                    rest.len() == 3
                        && rest.starts_with('z')
                        && rest[1..].chars().all(|ch| ch.is_ascii_digit())
                });
            if is_base || is_split {
                push(path.clone());
            }
        }
    } else if lower.ends_with(".001") {
        // `Game.7z.001`, `Game.zip.001` or generic `Game.001`: the prefix keeps
        // any archive extension because it is part of the filename stem.
        let prefix = format!("{}.", &name[..name.len() - 4].to_ascii_lowercase());
        for (entry_lower, path) in &entries {
            let Some(rest) = entry_lower.strip_prefix(&prefix) else {
                continue;
            };
            if rest.len() == 3 && rest.chars().all(|ch| ch.is_ascii_digit()) {
                push(path.clone());
            }
        }
    } else {
        // Single `.7z` (or anything that reached this point without siblings).
        push(first.to_path_buf());
    }

    if volumes.is_empty() {
        volumes.push(first.to_path_buf());
    }
    volumes.sort_by(|left, right| {
        left.file_name()
            .map(|name| name.to_string_lossy().to_lowercase())
            .cmp(&right.file_name().map(|name| name.to_string_lossy().to_lowercase()))
    });
    volumes
}

/// Move every original volume to the Recycle Bin after a successful extraction.
fn remove_originals(first: &Path) -> (Vec<String>, Option<String>) {
    let existing: Vec<PathBuf> = archive_volumes(first)
        .into_iter()
        .filter(|path| path.is_file())
        .collect();
    if existing.is_empty() {
        return (Vec::new(), None);
    }
    match recycle_files(&existing) {
        Ok(()) => (
            existing
                .iter()
                .map(|path| path.to_string_lossy().into_owned())
                .collect(),
            None,
        ),
        Err(error) => (
            Vec::new(),
            Some(format!("原压缩包未能移入回收站：{error}")),
        ),
    }
}

#[cfg(windows)]
fn recycle_files(paths: &[PathBuf]) -> Result<(), String> {
    use std::os::windows::ffi::OsStrExt;
    use windows_sys::Win32::UI::Shell::{
        SHFileOperationW, SHFILEOPSTRUCTW, FO_DELETE, FOF_ALLOWUNDO, FOF_NOCONFIRMATION,
        FOF_NOERRORUI, FOF_SILENT,
    };

    let mut from: Vec<u16> = Vec::new();
    for path in paths {
        for unit in path.as_os_str().encode_wide() {
            from.push(unit);
        }
        from.push(0);
    }
    from.push(0); // double-NUL termination required by SHFileOperationW

    let mut operation: SHFILEOPSTRUCTW = unsafe { std::mem::zeroed() };
    operation.wFunc = FO_DELETE as u32;
    operation.pFrom = from.as_ptr();
    operation.fFlags = (FOF_ALLOWUNDO | FOF_NOCONFIRMATION | FOF_SILENT | FOF_NOERRORUI) as u16;

    let code = unsafe { SHFileOperationW(&mut operation) };
    if code == 0 {
        Ok(())
    } else {
        Err(format!("回收站操作失败（错误码 {code}）"))
    }
}

#[cfg(not(windows))]
fn recycle_files(_paths: &[PathBuf]) -> Result<(), String> {
    Err("当前系统不支持回收站删除".to_string())
}

fn parse_progress(line: &str) -> Option<u8> {
    let trimmed = line.trim_start();
    let percent_index = trimmed.find('%')?;
    let digits: String = trimmed[..percent_index]
        .chars()
        .rev()
        .take_while(|ch| ch.is_ascii_digit())
        .collect::<Vec<_>>()
        .into_iter()
        .rev()
        .collect();
    digits
        .parse::<u8>()
        .ok()
        .map(|value| value.min(100))
}

/// Result of probing an archive with `7z l -slt`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Probe {
    /// Not encrypted (or metadata is readable).
    Clean,
    /// Files are encrypted; listing without a password still works.
    Encrypted,
    /// Listing itself needs a password (header-encrypted RAR/7z) or the password
    /// supplied was rejected.
    PasswordProblem,
}

fn probe_archive(seven_zip: &Path, archive: &Path, password: Option<&str>) -> Probe {
    let mut command = Command::new(seven_zip);
    command
        .arg("l")
        .arg("-slt")
        .arg(archive)
        .arg("-y")
        .stdin(Stdio::null())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped());
    if let Some(password) = password.map(str::trim).filter(|value| !value.is_empty()) {
        command.arg(format!("-p{password}"));
    }
    #[cfg(windows)]
    {
        use std::os::windows::process::CommandExt;
        const CREATE_NO_WINDOW: u32 = 0x0800_0000;
        command.creation_flags(CREATE_NO_WINDOW);
    }

    let output = match command.output() {
        Ok(output) => output,
        Err(_) => return Probe::Clean,
    };
    let mut text = String::from_utf8_lossy(&output.stdout).to_ascii_lowercase();
    text.push_str(&String::from_utf8_lossy(&output.stderr).to_ascii_lowercase());
    if output.status.success() {
        if text.contains("encrypted = +") {
            Probe::Encrypted
        } else {
            Probe::Clean
        }
    } else if text.contains("wrong password")
        || text.contains("encrypted")
        || text.contains("password")
    {
        Probe::PasswordProblem
    } else {
        // Corrupt or unsupported archive; let the extraction attempt report it.
        Probe::Clean
    }
}

/// Classify a failed 7-Zip run from its textual output.
fn classify_output(output: &str, used_password: bool) -> ExtractStatus {
    let lower = output.to_ascii_lowercase();
    let password_related = lower.contains("wrong password")
        || lower.contains("encrypted archive")
        || lower.contains("enter password")
        || lower.contains("can not open encrypted");
    if !password_related {
        return ExtractStatus::Failed;
    }
    if used_password {
        ExtractStatus::WrongPassword
    } else {
        ExtractStatus::PasswordRequired
    }
}

/// Locate the bundled `7z.exe`, extracting it on first use.
pub(crate) fn seven_zip_path(app: &AppHandle) -> CmdResult<PathBuf> {
    let directory = app
        .path()
        .app_local_data_dir()
        .map_err(|error| CmdError(error.to_string()))?
        .join("tools")
        .join("7zip")
        .join(BUNDLED_VERSION);
    std::fs::create_dir_all(&directory)
        .map_err(|error| CmdError(format!("无法准备内置 7-Zip：{error}")))?;
    for (relative, bytes) in BUNDLED_FILES {
        let path = directory.join(relative);
        if path.is_file() {
            continue;
        }
        std::fs::write(&path, bytes)
            .map_err(|error| CmdError(format!("内置 7-Zip 文件准备失败 {relative}：{error}")))?;
    }
    let executable = directory.join("7z.exe");
    if !executable.is_file() {
        return Err(CmdError("内置 7-Zip 缺少 7z.exe".to_string()));
    }
    Ok(executable)
}

